// Acak tanpa pengulangan sampai semua kalimat tampil, lalu acak ulang.
export function kalimatBerikut(storage = localStorage, acak = Math.random) {
  let st;
  try { st = JSON.parse(storage.getItem('bukue:kalimat') || 'null'); } catch { st = null; }
  if (!st || !Array.isArray(st.urut) || st.urut.length !== SEMUA.length || st.i >= st.urut.length) {
    const terakhir = st?.urut?.[st.urut.length - 1];
    const urut = SEMUA.map((_, i) => i);
    for (let i = urut.length - 1; i > 0; i--) { const j = Math.floor(acak() * (i + 1)); [urut[i], urut[j]] = [urut[j], urut[i]]; }
    if (urut[0] === terakhir) [urut[0], urut[1]] = [urut[1], urut[0]];
    st = { urut, i: 0 };
  }
  const k = SEMUA[st.urut[st.i]];
  st.i++;
  storage.setItem('bukue:kalimat', JSON.stringify(st));
  return k;
}

